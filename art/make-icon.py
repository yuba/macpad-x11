#!/usr/bin/env python3
"""Draw the macpad-x11 icon (icon.svg) and the GitHub social preview (social-preview.svg).

The icon is an emoji-yellow right hand resting three fingers on a trackpad.
Render PNGs with e.g.: rsvg-convert -w 1280 social-preview.svg -o social-preview.png
"""
import math
import os

# The hand is drawn in a local frame with the fingers pointing up (-y) and
# the middle fingertip at the origin, then rotated so that the fingers point
# up-left, coming in from the lower right at 30 degrees above horizontal.
ANGLE = -60          # rotates local "up" to (-cos 30, -sin 30)
TIP = (262, 250)     # middle fingertip on the 512x512 icon
W = 56               # finger width
GAP = 6              # between neighbouring fingers
KNUCKLE = 160        # where the back of the hand starts, behind the middle fingertip
TIPS = (16, 0, 10)   # how far each fingertip (index, middle, ring) sits behind the middle one
BLUE = "#0a84ff"


def arc(cx, cy, r, start, end):
    """SVG path of a circular arc from angle start to end (degrees, 0 = +x, clockwise)."""
    a, b = math.radians(start), math.radians(end)
    return (f"M{cx + r * math.cos(a):.1f} {cy + r * math.sin(a):.1f} "
            f"A{r:.1f} {r:.1f} 0 0 1 {cx + r * math.cos(b):.1f} {cy + r * math.sin(b):.1f}")


def hand():
    xs = (-(W + GAP), 0, W + GAP)
    shapes = [f'<rect x="{x - W / 2}" y="{t}" width="{W}" height="{KNUCKLE + W - t}" rx="{W / 2}"/>'
              for x, t in zip(xs, TIPS)]
    # The back of the hand continues the outer edges of the index and ring
    # fingers and runs off the lower right corner.
    left, right = xs[0] - W / 2, xs[2] + W / 2
    shapes.append(f'<rect x="{left}" y="{KNUCKLE}" width="{right - left}" height="400"/>')
    shapes = "".join(shapes)
    ripples = []
    for x, t in zip(xs, TIPS):
        cy = t + W * 0.45           # contact point under the fingertip
        ripples.append(f'<circle cx="{x}" cy="{cy:.1f}" r="{W * 0.8:.1f}" fill="none" '
                       f'stroke="{BLUE}" stroke-width="7" opacity="0.55"/>')
        # Arcs ahead of the fingertip (local up is -90 degrees).
        for r, op in ((W * 1.15, 0.45), (W * 1.5, 0.25)):
            ripples.append(f'<path d="{arc(x, cy, r, -125, -55)}" fill="none" stroke="{BLUE}" '
                           f'stroke-width="7" stroke-linecap="round" opacity="{op}"/>')
    # Outline first, then the fill on top: one silhouette, with the outline
    # showing in the gaps between the fingers.
    return (f'<g transform="translate({TIP[0]} {TIP[1]}) rotate({ANGLE})">'
            f'{"".join(ripples)}'
            f'<g fill="#E8A317" stroke="#C47F00" stroke-width="12" stroke-linejoin="round">{shapes}</g>'
            f'<g fill="#FFCC4D">{shapes}</g></g>')


def icon_body(ns):
    """The 512x512 icon as SVG elements; ns keeps ids unique when embedded."""
    return f'''<defs>
    <linearGradient id="{ns}-bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#3a3f47"/><stop offset="1" stop-color="#1c1f24"/>
    </linearGradient>
    <clipPath id="{ns}-shape"><rect width="512" height="512" rx="112"/></clipPath>
  </defs>
  <g clip-path="url(#{ns}-shape)">
    <rect width="512" height="512" fill="url(#{ns}-bg)"/>
    <rect x="56" y="100" width="400" height="312" rx="44" fill="#e9ecf0" stroke="#c3c8cf" stroke-width="6"/>
    {hand()}
  </g>'''


ICON = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <!-- macpad-x11: an emoji-yellow right hand resting three fingers on a trackpad.
       Generated by make-icon.py. -->
  {icon_body("icon")}
</svg>
'''

PREVIEW = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1280 640">
  <!-- GitHub social preview (1280x640). Generated by make-icon.py. -->
  <rect width="1280" height="640" fill="#16181c"/>
  <g transform="translate(120 140) scale(0.703125)">
  {icon_body("preview")}
  </g>
  <g font-family="Noto Sans, DejaVu Sans, sans-serif" fill="#f2f3f5">
    <text x="560" y="290" font-size="92" font-weight="700">macpad-x11</text>
    <text x="562" y="360" font-size="34" fill="#c3c8cf">macOS-style touchpad gestures for X11</text>
    <text x="562" y="430" font-size="25" fill="#8e9399">three-finger drag · pinch to zoom around the pointer</text>
  </g>
</svg>
'''

here = os.path.dirname(os.path.realpath(__file__))
for name, svg in (("icon.svg", ICON), ("social-preview.svg", PREVIEW)):
    with open(os.path.join(here, name), "w") as fh:
        fh.write(svg)
